function applyRestaurantContent() {
  if (!restaurantContent) return;
  const address = restaurantContent.address || "";
  const city = restaurantContent.city || "";
  const postalCode = restaurantContent.postal_code || "";
  const country = restaurantContent.country || "";
  const cityLine = [city, postalCode].filter(Boolean).join(" ");
  const locationLine = [cityLine, country].filter(Boolean).join(", ");
  const phone = restaurantContent.phone || "";
  const phoneLink = `tel:${phone.replace(/[^\d+]/g, "")}`;
  const hours = restaurantContent.hours?.[activeLanguage]
    || restaurantContent.hours?.en
    || "Opening hours unavailable";
  const serviceLabel = {
    sq: "Në lokal · Për takeaway",
    it: "Sul posto · Da asporto",
    en: "Dine-in · Takeaway"
  }[activeLanguage];

  document.querySelectorAll("[data-restaurant-address]").forEach((element) => {
    element.textContent = address;
  });
  document.querySelectorAll("[data-restaurant-location]").forEach((element) => {
    element.textContent = locationLine;
  });
  document.querySelectorAll("[data-restaurant-phone]").forEach((element) => {
    element.href = phoneLink;
    if (element.hasAttribute("data-phone-display")) element.textContent = phone;
  });
  document.querySelectorAll("[data-restaurant-phone-link]").forEach((element) => {
    element.href = phoneLink;
  });
  document.querySelectorAll("[data-restaurant-hours]").forEach((element) => {
    element.textContent = hours;
  });
  document.querySelector("[data-restaurant-footer-hours]").textContent = `${hours} · ${serviceLabel}`;
  document.querySelector("[data-restaurant-map-label]").textContent = `${address} · ${city}`;

  const destination = `Bukë e Zemër, ${address}, ${cityLine}, ${country}`;
  const query = encodeURIComponent(destination);
  document.querySelector("[data-restaurant-map]").src = `https://maps.google.com/maps?q=${query}&t=&z=15&ie=UTF8&iwloc=&output=embed`;
  document.querySelectorAll("[data-restaurant-directions]").forEach((element) => {
    element.href = `https://www.google.com/maps/dir/?api=1&destination=${query}`;
  });
  document.querySelector("[data-restaurant-map-search]").href = `https://www.google.com/maps/search/?api=1&query=${query}`;

  const schemaElement = document.querySelector("#restaurant-schema");
  const schema = JSON.parse(schemaElement.textContent);
  schema.telephone = phone;
  schema.address.streetAddress = address;
  schema.address.addressLocality = city;
  schema.address.postalCode = postalCode;
  schema.address.addressCountry = country;
  schemaElement.textContent = JSON.stringify(schema);
}

async function syncPublicContent() {
  try {
    const client = await backendClientPromise;
    if (!client) return;
    const [contentResult, menuResult] = await Promise.all([
      client.from("restaurant_content").select("content").eq("id", "main").maybeSingle(),
      client.from("menu_items")
        .select("id,name,description,category,price,image_url,is_available,sort_order")
        .eq("is_available", true)
        .order("sort_order", { ascending: true })
    ]);
    if (contentResult.error) throw contentResult.error;
    if (menuResult.error) throw menuResult.error;

    restaurantContent = contentResult.data?.content || null;
    applyRestaurantContent();
    menuItems = (menuResult.data || []).map((item) => ({
      name: item.name?.en || item.name?.sq || "",
      category: item.category?.en || item.category?.sq || "",
      description: item.description?.en || item.description?.sq || "",
      price: `€${Number(item.price).toFixed(2)}`,
      image: item.image_url || "",
      localized: Object.fromEntries(["sq", "it", "en"].map((language) => [
        language,
        {
          name: item.name?.[language] || item.name?.en || item.name?.sq || "",
          description: item.description?.[language] || "",
          category: item.category?.[language] || item.category?.en || item.category?.sq || ""
        }
      ]))
    }));
    selectedCategory = "All";
    renderMenu();
    showBackendNotice(menuItems.length ? "" : "empty");
  } catch (error) {
    console.error("Could not load live restaurant content from Supabase.", error);
    showBackendNotice("offline");
  }
}

