function renderMenu() {
  menuCategories = [...new Set(menuItems.map((item) => item.category))];
  menuFilters.replaceChildren();

  ["All", ...menuCategories].forEach((category) => {
    const filter = document.createElement("button");
    filter.type = "button";
    filter.className = "filter-button";
    filter.textContent = category === "All"
      ? ({ sq: "Të gjitha", it: "Tutti", en: "All" })[activeLanguage]
      : menuCategoriesCopy[activeLanguage][category] || category;
    filter.setAttribute("aria-pressed", String(category === selectedCategory));
    filter.addEventListener("click", () => {
      selectedCategory = category;
      renderMenu();
    });
    menuFilters.append(filter);
  });

  const visibleItems = selectedCategory === "All"
    ? menuItems
    : menuItems.filter((item) => item.category === selectedCategory);

  menuGrid.replaceChildren(...visibleItems.map((item, index) => {
    const managedItem = item.localized?.[activeLanguage];
    const localizedItem = menuItemCopy[activeLanguage][item.name];
    const itemName = managedItem?.name || (localizedItem ? localizedItem[0] : item.name);
    const itemDescription = managedItem?.description ?? (localizedItem ? localizedItem[1] : item.description);
    const categoryName = managedItem?.category || menuCategoriesCopy[activeLanguage][item.category] || item.category;
    const article = document.createElement("article");
    article.className = "menu-card";
    article.style.animationDelay = `${Math.min(index, 8) * 35}ms`;

    const imageWrap = document.createElement("div");
    imageWrap.className = "menu-card-image";
    const image = document.createElement("img");
    if (item.image) {
      image.src = item.image.startsWith("assets/")
        ? item.image
        : item.image.startsWith("http")
          ? item.image
          : `https://images.unsplash.com/${item.image}?auto=format&fit=crop&w=720&q=78`;
    } else {
      image.removeAttribute("src");
    }
    image.alt = itemName;
    image.loading = "lazy";
    const category = document.createElement("span");
    category.className = "menu-card-category";
    category.textContent = categoryName;
    imageWrap.append(image, category);

    const copy = document.createElement("div");
    copy.className = "menu-card-copy";
    const title = document.createElement("h3");
    title.textContent = itemName;
    const price = document.createElement("span");
    price.className = "menu-price";
    price.textContent = item.price;
    copy.append(title, price);

    article.append(imageWrap, copy);
    if (itemDescription) {
      const description = document.createElement("p");
      description.textContent = itemDescription;
      article.append(description);
    }
    return article;
  }));
}

