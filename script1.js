const reservationDate = reservationForm.elements.date;
const today = new Date();
today.setMinutes(today.getMinutes() - today.getTimezoneOffset());
reservationDate.min = today.toISOString().slice(0, 10);

reservationForm.addEventListener("submit", async (event) => {
  event.preventDefault();
  if (!reservationForm.reportValidity()) return;

  const values = new FormData(reservationForm);
  const labels = reservationLabels[activeLanguage];
  const lines = [
    `${labels.name}: ${values.get("name")}`,
    `${labels.phone}: ${values.get("phone")}`,
    `${labels.date}: ${values.get("date")}`,
    `${labels.time}: ${values.get("time")}`,
    `${labels.guests}: ${values.get("guests")}`
  ];
  const message = String(values.get("message") || "").trim();
  if (message) lines.push(`${labels.message}: ${message}`);

  const submitButton = reservationForm.querySelector('[type="submit"]');
  submitButton.disabled = true;
  try {
    const client = await backendClientPromise;
    if (client) {
      const { error } = await client.from("reservations").insert({
        customer_name: String(values.get("name")).trim(),
        phone: String(values.get("phone")).trim(),
        reservation_date: values.get("date"),
        reservation_time: values.get("time"),
        guests: Number(values.get("guests")),
        message
      });
      if (error) throw error;
      reservationStatus.textContent = languageMeta[activeLanguage].reservationSaved;
      reservationForm.reset();
      reservationDate.min = today.toISOString().slice(0, 10);
      return;
    }

    const subject = {
      sq: "Kërkesë për rezervim — Bukë e Zemër",
      it: "Richiesta di prenotazione — Bukë e Zemër",
      en: "Table reservation request — Bukë e Zemër"
    }[activeLanguage];
    const emailLink = document.createElement("a");
    emailLink.href = `mailto:bukezemer.r@gmail.com?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(lines.join("\n"))}`;
    emailLink.textContent = languageMeta[activeLanguage].mailLink;
    emailLink.className = "reservation-mail-link";
    reservationStatus.replaceChildren(
      document.createTextNode(`${languageMeta[activeLanguage].status} `),
      emailLink
    );
  } catch (error) {
    console.error("Could not save the reservation request.", error);
    reservationStatus.textContent = languageMeta[activeLanguage].reservationError;
  } finally {
    submitButton.disabled = false;
  }
});

