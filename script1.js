function setLanguage(language) {
  activeLanguage = language;
  document.documentElement.lang = language;
  document.title = languageMeta[language].title;
  document.querySelector('meta[name="description"]').content = languageMeta[language].description;
  document.querySelector('meta[property="og:title"]').content = languageMeta[language].ogTitle;
  document.querySelector('meta[property="og:description"]').content = languageMeta[language].description;

  originalTextNodes.forEach(({ node, original, key }) => {
    const translation = textCopy[key] || textCopy[` ${key}`];
    if (!translation) return;
    const leading = original.match(/^\s*/)[0];
    const trailing = original.match(/\s*$/)[0];
    node.nodeValue = `${leading}${translation[localeIndex[language]]}${trailing}`;
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });

  const meta = languageMeta[language];
  document.querySelector(".hero-image").alt = meta.heroAlt;
  document.querySelector(".story-main-image").alt = meta.storyMainAlt;
  document.querySelector(".story-inset img").alt = meta.storyInsetAlt;
  nav.setAttribute("aria-label", meta.nav);
  document.querySelectorAll(".language-switch").forEach((group) => group.setAttribute("aria-label", meta.choose));
  navToggle.setAttribute("aria-label", navToggle.getAttribute("aria-expanded") === "true" ? meta.closeNav : meta.openNav);
  document.querySelector(".menu-filters").setAttribute("aria-label", ({
    sq: "Filtro sipas kategorisë",
    it: "Filtra per categoria",
    en: "Filter menu by category"
  })[language]);
  document.querySelector(".lightbox").setAttribute("aria-label", ({
    sq: "Fotografia e galerisë",
    it: "Immagine della galleria",
    en: "Gallery image"
  })[language]);
  document.querySelector(".lightbox-close").setAttribute("aria-label", meta.closeImage);
  document.querySelector(".lightbox-prev").setAttribute("aria-label", meta.previousImage);
  document.querySelector(".lightbox-next").setAttribute("aria-label", meta.nextImage);
  document.querySelector(".map-frame iframe").title = meta.map;
  document.querySelector(".reservation-close").setAttribute("aria-label", meta.closeReservation);
  applyRestaurantContent();

  document.querySelectorAll(".gallery-item").forEach((item, index) => {
    const [caption, label, alt] = galleryCopy[language][index];
    item.dataset.caption = caption;
    item.setAttribute("aria-label", `${meta.gallery}: ${label}`);
    item.querySelector("img").alt = alt;
  });

  if (lightbox.open) showGalleryImage(activeImageIndex);
  renderMenu();
}

